// Build the programme pages (one per IDEA Malta hero programme, one per
// Fondazione Doria stream) from data/programme-pages.json + data/programmes.json.
//
//   node tools/build-catalogue.mjs && node tools/build-programme-pages.mjs && node tools/critical-css.mjs
//
// Pages are written to the site root (e.g. /bsc-computing-malta) using the
// finder page's head, header and footer, so they share its styles and
// performance setup. Each page carries Course structured data (schema.org).
// Fails (exit 1) if a page's programme is missing from the catalogue.

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const read = (f) => fs.readFileSync(path.join(ROOT, f), "utf8");
const SITE = "https://primegateconsultancy.com";
const esc = (s) => String(s).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
const euro = (n) => "€" + Number(n).toLocaleString("en-GB");
const years = (n) => n + (n === 1 ? " year" : " years");
const iso = (y) => (Number.isInteger(y) ? `P${y}Y` : `P${Math.round(y * 12)}M`);
const json = (o) => JSON.stringify(o).replace(/</g, "\\u003c");

const content = JSON.parse(read("data/programme-pages.json"));
const cat = JSON.parse(read("data/programmes.json"));
const inst = Object.fromEntries(cat.institutions.map((i) => [i.id, i]));
const byTitle = (i, t) => cat.programmes.find((p) => p.i === i && p.t === t);
const errors = [];

// ---- shared page shell from programmes.html ----
const base = read("programmes.html");
const headTpl = base.slice(0, base.indexOf("<body"));
const header = base.slice(base.indexOf("<header"), base.indexOf("</header>") + 9)
  .replace(' class="active" aria-current="page">Find Your Programme', ">Find Your Programme");
const footer = base.slice(base.indexOf("<footer"), base.indexOf("</footer>") + 9);
const mainJs = (base.match(/<script src="js\/main\.js\?v=[^"]+"><\/script>/) || [""])[0];

function page({ slug, title, description, crumbs, body, ld }) {
  const url = `${SITE}/${slug}`;
  let head = headTpl
    .replace(/<title>[^<]*<\/title>/, `<title>${esc(title)} | Primegate Consultancy</title>`)
    .replace(/<meta name="description" content="[^"]*" \/>/, `<meta name="description" content="${esc(description)}" />`)
    .replace(/<link rel="canonical" href="[^"]*" \/>/, `<link rel="canonical" href="${url}" />`)
    .replace(/<meta property="og:title" content="[^"]*" \/>/, `<meta property="og:title" content="${esc(title)} | Primegate Consultancy" />`)
    .replace(/<meta property="og:description" content="[^"]*" \/>/, `<meta property="og:description" content="${esc(description)}" />`)
    .replace(/<meta property="og:url" content="[^"]*" \/>/, `<meta property="og:url" content="${url}" />`)
    .replace(/<script type="application\/ld\+json">[\s\S]*?<\/script>\s*/g, "");
  const breadcrumb = { "@context": "https://schema.org", "@type": "BreadcrumbList", itemListElement: crumbs.map(([name, href], i) => ({ "@type": "ListItem", position: i + 1, name, item: SITE + href })) };
  head = head.replace("</head>", `<script type="application/ld+json">\n${json(breadcrumb)}\n</script>\n<script type="application/ld+json">\n${json(ld)}\n</script>\n</head>`);
  const crumbHtml = crumbs.map(([name, href], i) => (i < crumbs.length - 1 ? `<a href="${href}">${esc(name)}</a>` : esc(name))).join(" / ");
  return `${head}<body class="solid-header">\n\n<!-- generated by tools/build-programme-pages.mjs from data/programme-pages.json - do not edit by hand -->\n${header}\n\n${body.replace("<!--crumbs-->", crumbHtml)}\n\n${footer}\n\n${mainJs}\n</body>\n</html>\n`;
}

const facts = (rows) => `<dl class="pfacts">\n${rows.filter(([, v]) => v).map(([k, v]) => `      <div><dt>${esc(k)}</dt><dd>${v}</dd></div>`).join("\n")}\n    </dl>`;
const list = (items, cls = "ticks") => `<ul class="${cls}">\n${items.map((x) => `        <li>${esc(x)}</li>`).join("\n")}\n      </ul>`;
const cta = (id, label) => `<section class="section section--navy center prog-cta">
  <div class="wrap measure center">
    <h2>Talk to a Primegate Consultancy advisor</h2>
    <p>Your advisor confirms entry, fees and the next intake for your situation, and supports you from application to arrival.</p>
    <div class="btn-row" style="justify-content:center;margin-top:1.4rem;"><a href="/contact?${id}#contact-forms" class="btn btn--gold">${esc(label)}</a><a href="/programmes" class="btn btn--ghost">Find Your Programme</a></div>
  </div>
</section>`;
const written = [];

// ---- IDEA College, Malta: one page per hero programme ----
const ideaInfo = content.institutions["idea-malta"];
const ideaPages = content.idea.map((c) => ({ c, p: byTitle("idea-malta", c.match) }));
ideaPages.forEach(({ c, p }) => { if (!p) errors.push("IDEA programme not in catalogue: " + c.match); });
if (errors.length) { console.error(errors.join("\n")); process.exit(1); }

ideaPages.forEach(({ c, p }, idx) => {
  const i = inst["idea-malta"];
  const level = cat.levels[p.lv];
  const award = `${level} (${p.fw})`;
  const related = ideaPages.filter((x) => x !== ideaPages[idx]).map(({ c: rc, p: rp }) => `<li><a href="/${rc.slug}">${esc(rp.t)}</a> <span>${esc(rp.fw)} · ${euro(rp.fee)}</span></li>`).join("\n        ");
  const desc = `${p.t}, IDEA College Malta: ${p.fw}, ${p.cr}, ${years(p.yr)}, fee ${euro(p.fee)}. Modules, entry and careers.`;
  const body = `<section class="page-head">
  <div class="wrap">
    <nav class="crumbs" aria-label="Breadcrumb"><!--crumbs--></nav>
    <p class="prog-kicker">IDEA College, Malta · ${esc(award)}</p>
    <h1>${esc(p.t)}</h1>
    <p>${esc(c.overview.split(/(?<=\.)\s/)[0])}</p>
    <div class="btn-row"><a href="/contact?programme=${p.id}#contact-forms" class="btn btn--gold">Ask about this programme</a><a href="/programmes?programme=${p.id}" class="btn btn--ghost">Compare in Find Your Programme</a></div>
  </div>
</section>

<section class="section prog-page">
  <div class="wrap">
    <h2 class="sr-only">Key facts</h2>
    ${facts([
      ["Institution", `<a href="/idea-college-malta">IDEA College, Malta</a>`],
      ["Award", esc(award)],
      ["Credits", esc(p.cr)],
      ["Duration", esc(years(p.yr))],
      ["Study load", esc(ideaInfo.study_load)],
      ["Language", esc(ideaInfo.language)],
      ["Location", esc(ideaInfo.location)],
      ["Intakes", esc(ideaInfo.intake)],
      [p.fl, `<strong>${euro(p.fee)}</strong>`],
      ...(p.ex ? [["Next exit point", esc(p.ex)]] : []),
    ])}
    <div class="prog-body">
      <h2>Programme overview</h2>
      <p>${esc(c.overview)}</p>
      <h2>Who it is for</h2>
      ${list(c.who)}
      <h2>What you will study</h2>
      ${list(c.modules, "ticks prog-modules")}
      <h2>Entry requirements</h2>
      ${list(c.entry, "prog-entry")}
      <p class="prog-note">An advisor will confirm how your qualification maps to these requirements.</p>
      <h2>Career paths</h2>
      ${list(c.careers)}
      <h2>Fees and intakes</h2>
      <p>${esc(p.fl)}: <strong>${euro(p.fee)}</strong> for the full programme (${esc(years(p.yr))}). Intakes run ${esc(ideaInfo.intake.toLowerCase())}; your Primegate Consultancy advisor confirms the fee and next start date for your situation.</p>
      <h2>More IDEA College programmes</h2>
      <ul class="prog-related">
        ${related}
      </ul>
    </div>
  </div>
</section>

${cta("programme=" + p.id, "Ask about this programme")}`;
  const ld = {
    "@context": "https://schema.org", "@type": "Course", name: p.t, url: `${SITE}/${c.slug}`, description: c.overview,
    provider: { "@type": "CollegeOrUniversity", name: "IDEA College, Malta", url: `${SITE}/idea-college-malta` },
    educationalCredentialAwarded: `${award}, ${p.cr}`,
    numberOfCredits: { "@type": "StructuredValue", value: parseInt(p.cr, 10), unitText: "ECTS" },
    timeRequired: iso(p.yr), inLanguage: "en", coursePrerequisites: c.entry, teaches: c.modules,
    offers: { "@type": "Offer", category: p.fl, price: p.fee, priceCurrency: "EUR" },
    hasCourseInstance: { "@type": "CourseInstance", courseMode: "Blended", location: { "@type": "Place", name: "Malta" } },
  };
  fs.writeFileSync(path.join(ROOT, c.slug + ".html"), page({
    slug: c.slug, title: c.seo_title || `${p.t} - IDEA College Malta`, description: desc,
    crumbs: [["Home", "/"], ["Find Your Programme", "/programmes"], ["IDEA College, Malta", "/idea-college-malta"], [p.t, "/" + c.slug]],
    body, ld,
  }));
  written.push(c.slug);
});

// ---- Fondazione Doria: one page per stream ----
const fdInfo = content.institutions["fondazione-doria"];
const fdNames = { health: "Healthcare & Social Care", construction: "Construction & Technical Trades", hospitality: "Hospitality, Tourism & Culinary", fashion: "Fashion, Beauty & Personal Care", it: "IT, Digital & Automation" };
const owner = JSON.parse(read("data/owner-programme-facts.json"))["fondazione-doria"].programmes;
content.doria.forEach((c) => {
  const rows = cat.programmes.filter((p) => p.i === "fondazione-doria" && owner[p.t] && owner[p.t].stream === c.stream);
  if (!rows.length) { errors.push("No Doria programmes for stream " + c.stream); return; }
  const fees = rows.map((r) => r.fee);
  const range = Math.min(...fees) === Math.max(...fees) ? euro(fees[0]) : `${euro(Math.min(...fees))} - ${euro(Math.max(...fees))}`;
  const others = content.doria.filter((o) => o !== c).map((o) => `<li><a href="/${o.slug}">${esc(o.title)}</a></li>`).join("\n        ");
  const desc = `${rows.length} ${fdNames[c.stream]} courses in Campania, Italy (2026-27): fees ${range}, monthly intakes.`;
  const body = `<section class="page-head">
  <div class="wrap">
    <nav class="crumbs" aria-label="Breadcrumb"><!--crumbs--></nav>
    <p class="prog-kicker">Fondazione Doria · ${esc(fdNames[c.stream])} · 2026-27</p>
    <h1>${esc(c.title)}</h1>
    <p>${esc(c.overview.split(/(?<=\.)\s/)[0])}</p>
    <div class="btn-row"><a href="/contact?institution=fondazione-doria#contact-forms" class="btn btn--gold">Ask about these courses</a><a href="/programmes?institution=fondazione-doria" class="btn btn--ghost">Search in Find Your Programme</a></div>
  </div>
</section>

<section class="section prog-page">
  <div class="wrap">
    <h2 class="sr-only">Key facts</h2>
    ${facts([
      ["Institution", `<a href="/fondazione-doria">Fondazione Doria - Training and Education Institute</a>`],
      ["Programmes", `${rows.length} in this stream`],
      ["Course fee", `<strong>${range}</strong>`],
      ["Location", esc(fdInfo.location)],
      ["Intakes", esc(fdInfo.intake)],
      ["Internship", esc(fdInfo.internship)],
    ])}
    <div class="prog-body">
      <h2>About this stream</h2>
      <p>${esc(c.overview)}</p>
      ${list(c.highlights)}
      <h2>Programmes and course fees</h2>
      <div class="portfolio-table"><table>
        <thead><tr><th scope="col">Programme</th><th scope="col">Course fee</th></tr></thead>
        <tbody>
${rows.map((r) => `          <tr><th scope="row" data-label="Programme"><a href="/programmes?programme=${r.id}">${esc(r.t)}</a></th><td data-label="Course fee">${euro(r.fee)}</td></tr>`).join("\n")}
        </tbody>
      </table></div>
      <p class="prog-note">${esc(inst["fondazione-doria"].fn || "Fees are confirmed in writing at offer stage.")} Programme availability depends on intake availability, centre capacity, regulatory approval and Fondazione Doria confirmation.</p>
      <h2>Your journey to Italy</h2>
      <ol class="prog-steps">
        <li>Choose your programme and receive initial counselling from your Primegate Consultancy advisor.</li>
        <li>Submit your application and supporting documents; Fondazione Doria reviews the application.</li>
        <li>Receive your offer letter and complete the fee payment.</li>
        <li>Get assistance with the visa process and pre-departure requirements.</li>
        <li>Travel to Italy, begin your programme and progress toward the professional internship pathway.</li>
      </ol>
      <p class="prog-note">Fondazione Doria determines the authorised training centre for each student; a specific centre cannot be promised unless confirmed in writing.</p>
      <h2>Other Fondazione Doria streams</h2>
      <ul class="prog-related">
        ${others}
      </ul>
    </div>
  </div>
</section>

${cta("institution=fondazione-doria", "Ask about these courses")}`;
  const provider = { "@type": "EducationalOrganization", name: "Fondazione Doria - Training and Education Institute", url: `${SITE}/fondazione-doria` };
  const ld = {
    "@context": "https://schema.org", "@type": "ItemList", name: c.title, url: `${SITE}/${c.slug}`, numberOfItems: rows.length,
    itemListElement: rows.map((r, n) => ({
      "@type": "ListItem", position: n + 1,
      item: {
        "@type": "Course", name: r.t, description: `${r.t}: ${fdNames[c.stream]} vocational education and training programme at Fondazione Doria, Campania, Italy (2026-27).`,
        provider,
        offers: { "@type": "Offer", category: "Course fee", price: r.fee, priceCurrency: "EUR" },
        hasCourseInstance: { "@type": "CourseInstance", courseMode: "Onsite", location: { "@type": "Place", name: "Campania, Italy" } },
      },
    })),
  };
  fs.writeFileSync(path.join(ROOT, c.slug + ".html"), page({
    slug: c.slug, title: c.seo_title || c.title, description: desc,
    crumbs: [["Home", "/"], ["Find Your Programme", "/programmes"], ["Fondazione Doria", "/fondazione-doria"], [c.title, "/" + c.slug]],
    body, ld,
  }));
  written.push(c.slug);
});
if (errors.length) { console.error(errors.join("\n")); process.exit(1); }
fs.writeFileSync(path.join(ROOT, "data", "programme-pages.index.json"), JSON.stringify(written, null, 2) + "\n");
console.log(`programme pages: ${written.length} written (${ideaPages.length} IDEA, ${content.doria.length} Fondazione Doria)`);
